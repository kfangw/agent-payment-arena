#!/usr/bin/env python3
"""Write results/generated/lead_cells.json and results/generated/table_lead_rows.tex.

Nine main cells: Comp - B4 (refined grid) from the archived per-cell block sums
(results/archived_blocks/blocks_*.npz, keys A2, B4_refined, block_counts). E-fitted cells: Comp block sums from the E-fitted settlement
result (settlement_E-fitted_F*_mid_s*.json, regenerated by run.py) and B4 block
sums from the refined-grid B4 result (results/reference_b4/b4ref_*.json).
Per-cell 95% paired block bootstrap, 10,000 resamples, ratio of sums;
basis points of the declared mean exposure $49.50.

Usage: python3 scripts/make_lead_rows.py [<blocks_dir> [<efitted_runs_dir>]]
(defaults: results/archived_blocks, results/fitted_runs)
"""
import json
import sys
from pathlib import Path

import numpy as np

from paths import ARCHIVED_BLOCKS, REFERENCE_B4, RESULTS

GEN = RESULTS / "generated"
GEN.mkdir(parents=True, exist_ok=True)
blocks = Path(sys.argv[1]) if len(sys.argv) > 1 else ARCHIVED_BLOCKS
runs = Path(sys.argv[2]) if len(sys.argv) > 2 else RESULTS / "fitted_runs"
rng = np.random.default_rng(20260928)
B, DEN, MARGIN = 10_000, 49.5, 10.0


def ci(d, c):
    n = len(d)
    bs = np.empty(B)
    for j in range(B):
        i = rng.integers(0, n, n)
        bs[j] = d[i].sum() / c[i].sum()
    lo, hi = np.percentile(bs, [2.5, 97.5])
    return [round(float(x) / DEN * 1e4, 1) for x in (d.sum() / c.sum(), lo, hi)]


cells = [("E-fast", "F1", 1), ("E-fast", "F2", 2), ("E-fast", "F3", 3),
         ("E-slow", "F1", 4), ("E-slow", "F2", 5), ("E-slow", "F3", 6),
         ("E-outage", "F1", 7), ("E-outage", "F2", 8), ("E-outage", "F3", 9)]
kstar = {"E-fast": 1, "E-slow": 8, "E-outage": 0}
out = {}
for e, f, s in cells:
    z = np.load(blocks / f"blocks_{e}_{f}_mid_s{s}.npz")
    c = z["block_counts"].astype(float)
    out[f"{e} {f}"] = dict(b4_ref=ci(z["A2"] - z["B4_refined"], c), k=kstar[e])
for f, s in [("F1", 7), ("F2", 8), ("F3", 9)]:
    a = json.loads((runs / f"settlement_E-fitted_{f}_mid_s{s}.json").read_text())["payload"]
    b = json.loads((REFERENCE_B4 / f"b4ref_E-fitted_{f}_mid_s{s}.json").read_text())["payload"]
    c = np.asarray(a["block_counts"], float)
    d = np.asarray(a["policies"]["A"]["block_sums"]) - np.asarray(b["b4_block_sums"])
    out[f"E-fitted {f}"] = dict(b4_ref=ci(d, c), k=int(b["b4"]["k"]))

(GEN / "lead_cells.json").write_text(json.dumps(out, indent=1))
lines = []
for key, d in out.items():
    pt, lo, hi = d["b4_ref"]
    pos = "inside" if -MARGIN <= lo and hi <= MARGIN else ("above" if lo > MARGIN else ("straddles" if hi > MARGIN else "below"))
    cell = key.replace(" ", r"$\times$")
    sep = "\\addlinespace[1pt]\n" if key.endswith("F1") and not key.startswith("E-fast") else ""
    lines.append(f"{sep}{cell} & ${pt:+.1f}$ & $[{lo:+.1f},\\,{hi:+.1f}]$ & {d['k']} & {pos} \\\\")
(GEN / "table_lead_rows.tex").write_text("\n".join(lines) + "\n")
print("\n".join(lines))

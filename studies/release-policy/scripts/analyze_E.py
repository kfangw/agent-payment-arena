"""Summarise experiment E (spec: docs/spec-E.md sec 3, 4).  Reads results/measured_streams/[<tag>/]npz/law_L6.npz, law_L7.npz.

    export PYTHONPATH=$PWD/src && python3 scripts/analyze_E.py [--tag smoke] [--nb 1000]

Writes summary.json and summary.md next to the npz directory.

Statistics are computed by experiment H's analyse_law (same bootstrap: paired block, 1,000 resamples,
default_rng(20260930) restarted per law, 95% percentile intervals).  The reading rule of spec 4 is
applied to the point estimate of Comp - Cutoff in bp of the law's realized mean; intervals are reported.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import paths            # noqa: E402
import analyze_H as AH  # noqa: E402

ORDER = ("L6", "L7")
POL, PNAME, ACTS = AH.POL, AH.PNAME, AH.ACTS
MARGIN = AH.MARGIN
DESC = {"L6": "all listed Base facilitators, last 90 days (from 2026-07-02)",
        "L7": "Coinbase facilitator, its last 90 active days (2025-10-12 to 2026-01-09)"}
LIMIT = {"L6": "one facilitator list (a curated list), one chain (Base), a 90-day window, amounts binned to 3 significant figures",
         "L7": "one facilitator (Coinbase), one chain (Base), a 90-day window that ends on 2026-01-09 (not recent data), amounts binned to 3 significant figures"}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default=None)
    ap.add_argument("--nb", type=int, default=AH.NB)
    a = ap.parse_args(argv)
    run = paths.MEASURED_STREAMS / a.tag if a.tag else paths.MEASURED_STREAMS
    laws = [L for L in ORDER if (run / "npz" / f"law_{L}.npz").exists()]
    res = dict(unit="$ per payment; bp of the law's realized mean exposure", margin_bp=MARGIN,
               bootstrap=dict(resamples=a.nb, seed=AH.BSEED, kind="paired block (50 payments per block)"),
               data_source=json.loads((paths.X402_AMOUNTS / "hist.json").read_text())["source"], laws={})
    for L in laws:
        res["laws"][L] = AH.analyse_law(np.load(run / "npz" / f"law_{L}.npz"), a.nb)
    R = res["laws"]

    rr = {}
    for L in laws:
        x = R[L]
        d = x["diff_bp"]["cutoff"]
        inside = abs(d["point"]) <= MARGIN
        ci_in = -MARGIN <= d["ci"][0] and d["ci"][1] <= MARGIN
        sh = x["decomp"]["above_share_of_total"]
        cnt, val = x["dist"]["count_above_vstar"], x["dist"]["value_above_vstar"]
        head = (f"At {L} ({DESC[L]}; realized mean ${x['realized_mean']:.4f}), Comp - Cutoff = {d['point']:+.2f} bp "
                f"({x['diff_usd']['cutoff']['point']:+.3e} $ per payment), 95% interval [{d['ci'][0]:+.2f}, {d['ci'][1]:+.2f}] bp; "
                f"the point estimate is {'inside' if inside else 'outside'} the 10 bp margin.")
        if inside:
            body = " By the rule, the reading is: on measured sizes the policy equals a single cutoff."
        else:
            body = (f" By the rule, report the size and the share from payments above v*. The difference is {d['point']:+.2f} bp, "
                    f"of which the share from payments above v* is {'n/a' if sh is None else f'{100 * sh:.1f}%'}.")
        body += f" The interval {'lies inside' if ci_in else 'does not lie inside'} the margin."
        dist = (f" Payments above v* ($3.13) are {100 * cnt:.3f}% of the count and {100 * val:.2f}% of the value "
                f"(above the floor $1.90: {100 * x['dist']['count_above_floor']:.3f}% of the count, {100 * x['dist']['value_above_floor']:.2f}% of the value).")
        lim = f" Limits of the data: {LIMIT[L]}."
        rr[L] = dict(diff_bp=d, inside_margin=inside, ci_inside_margin=ci_in, above_vstar_share_of_diff=sh,
                     count_above_vstar=cnt, value_above_vstar=val, sentence=head + body + dist + lim)
    res["reading_rules"] = rr
    (run / "summary.json").write_text(json.dumps(res, indent=1))

    md = [f"# Experiment E summary (generated by analyze_E.py{', ' + a.tag if a.tag else ''})", ""]
    if a.tag:
        md += [f"This is a {a.tag} run. The numbers are not results.", ""]
    if laws:
        x0 = R[laws[0]]
        md += [f"Evaluation seed {x0['eval_seed']}, {x0['n_eval']:,} payments per law ({x0['n_blocks']:,} blocks). The four policies replay the same paths on each law. "
               f"Amounts are dollars per payment; bp is relative to the law's realized mean exposure. Intervals are 95% percentile intervals of a paired block bootstrap ({a.nb} resamples, seed {AH.BSEED}). "
               f"The margin is 10 bp. Cutoff threshold pihat(0) = {x0['pihat0']:.6f}, floor $1.90, v* $3.13. "
               f"The exposure law samples the point masses of an on-chain histogram (amounts binned to 3 significant figures) by inverse transform and clips to [0.01, 2000].", "",
               f"Data: {res['data_source']}", ""]
    md += ["## 1. Distribution", "",
           "| Law | Window | Histogram mean (after clip, exact) | Realized mean | Realized median | Count clipped at lower bound | Count clipped at upper bound | Count above floor | Value above floor | Count above v* | Value above v* |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for L in laws:
        x = R[L]
        md.append(f"| {L} | {DESC[L]} | {x['law']['mean_target']:.4f} | {x['realized_mean']:.4f} | {x['realized_median']:.4g} | "
                  f"{x['n_at_lo']:,} | {x['n_at_hi']:,} | {100 * x['dist']['count_above_floor']:.3f}% | {100 * x['dist']['value_above_floor']:.2f}% | "
                  f"{100 * x['dist']['count_above_vstar']:.3f}% | {100 * x['dist']['value_above_vstar']:.2f}% |")
    md += ["", "## 2. First action of Comp", "", "Shares by count and by value. The wait share is the share of payments that wait one tick or more.", "",
           "| Law | Basis | grant | reject | verify | wait |", "|---|---|---|---|---|---|"]
    for L in laws:
        f = R[L]["comp_first"]
        for k, nm in (("count", "count"), ("value", "value")):
            md.append(f"| {L} | {nm} | " + " | ".join(f"{100 * f[k][a_]:.3f}%" for a_ in ACTS) + " |")
    md += ["", "## 3. Payoff", "", "Dollars per payment.", "",
           "| Law | J(Comp) | J(Cutoff) | J(B4_L) | J(B4_L0) | B4_L (k, a, b) | B4_L0 (k, a, b) |", "|---|---|---|---|---|---|---|"]
    for L in laws:
        x = R[L]
        md.append(f"| {L} | " + " | ".join(f"{x['J'][p]['point']:.6g}" for p in POL)
                  + f" | ({x['b4L']['k']}, {x['b4L']['a']:.4f}, {x['b4L']['b']:.4f}) | ({x['b4L0']['k']}, {x['b4L0']['a']:.4f}, {x['b4L0']['b']:.4f}) |")
    md += ["", "| Law | Comparison | $ per payment | 95% interval ($) | bp | 95% interval (bp) |", "|---|---|---|---|---|---|"]
    for L in laws:
        x = R[L]
        for p in POL[1:]:
            du, db = x["diff_usd"][p], x["diff_bp"][p]
            md.append(f"| {L} | Comp - {PNAME[p]} | {du['point']:+.4e} | [{du['ci'][0]:+.3e}, {du['ci'][1]:+.3e}] | "
                      f"{db['point']:+.2f} | [{db['ci'][0]:+.2f}, {db['ci'][1]:+.2f}] |")
    md += ["", "## 4. Misuse release", "", "The pass rate is the share of misuse payments that are granted; the exposure is the sum of v over granted misuse payments divided by the number of payments.", "",
           "| Law | Policy | Pass rate | 95% interval | Exposure ($ per payment) | 95% interval | Exposure (bp) | Share of all payments granted |", "|---|---|---|---|---|---|---|---|"]
    for L in laws:
        x = R[L]
        for p in POL:
            m_, e_, b_ = x["misuse_pass_pct"][p], x["misuse_exposure_usd"][p], x["misuse_exposure_bp"][p]
            md.append(f"| {L} | {PNAME[p]} | {m_['point']:.3f}% | [{m_['ci'][0]:.3f}, {m_['ci'][1]:.3f}] | {e_['point']:.4e} | "
                      f"[{e_['ci'][0]:.3e}, {e_['ci'][1]:.3e}] | {b_['point']:.1f} | {x['grant_pct'][p]:.3f}% |")
    md += ["", "## 5. Decomposition of Comp - Cutoff", "", "Split into payments above v* (v > 3.13) and at or below it, and by the first action of Comp.", "",
           "| Law | Above v* ($) | 95% interval | Above v* (bp) | At or below v* ($) | 95% interval | At or below v* (bp) | Share above v* |", "|---|---|---|---|---|---|---|---|"]
    for L in laws:
        dc = R[L]["decomp"]
        sh = dc["above_share_of_total"]
        md.append(f"| {L} | {dc['above_vstar_usd']['point']:+.4e} | [{dc['above_vstar_usd']['ci'][0]:+.3e}, {dc['above_vstar_usd']['ci'][1]:+.3e}] | "
                  f"{dc['above_vstar_bp']['point']:+.2f} | {dc['below_vstar_usd']['point']:+.4e} | "
                  f"[{dc['below_vstar_usd']['ci'][0]:+.3e}, {dc['below_vstar_usd']['ci'][1]:+.3e}] | {dc['below_vstar_bp']['point']:+.2f} | "
                  f"{'' if sh is None else f'{100 * sh:.1f}%'} |")
    md += ["", "| Law | " + " | ".join(f"Comp {a_} (bp)" for a_ in ACTS) + " |", "|---|---|---|---|---|"]
    for L in laws:
        md.append(f"| {L} | " + " | ".join(f"{R[L]['by_comp_action_bp'][a_]:+.2f}" for a_ in ACTS) + " |")
    md += ["", "## 6. Reading (spec sec 4, applied to the point estimate)", ""]
    for L in laws:
        md += [f"({L}) {rr[L]['sentence']}", ""]
    (run / "summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return res


if __name__ == "__main__":
    main()
